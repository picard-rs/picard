/// Load the configuration from `config/picard` and `config/app`, or from the
/// paths in the `PICARD_CONF` and `APP_CONF` environment variables. Missing
/// files are skipped.
///
/// # Errors
///
/// Returns [`SystemError::Configuration`] if a file cannot be parsed or
/// does not match [`PicardConfig`].
pub fn load_config() -> Result<PicardConfig, SystemError> {
    // picard.toml contains settings for the actor framework and its modules
    let picard_path = env::var("PICARD_CONF").unwrap_or_else(|_| "config/picard".into());
    // app.toml or app.yaml contains settings specific to the user application
    let app_path = env::var("APP_CONF").unwrap_or_else(|_| "config/app".into());

    Ok(Config::builder()
        .add_source(config::File::with_name(&picard_path).required(false))
        .add_source(config::File::with_name(&app_path).required(false))
        .build()?
        .try_deserialize()?)
}

/// Wraps message and sender
#[derive(Debug, Clone)]
pub struct Envelope<T: LocalMessage> {
    pub sender: Option<BasicActorRef>,
    pub msg: T,
}

/// A value that can be delivered to an actor in this process.
///
/// This is the bound the runtime uses internally, including for the
/// messages of Picard's own actors (channels, system actors), which hold
/// actor references. Actors you create must use a [`Message`].
pub trait LocalMessage: Debug + Send + 'static {}
impl<T: Debug + Send + 'static> LocalMessage for T {}

/// A value that can be sent to an actor.
///
/// Messages need not be cloneable. APIs that fan out or repeat a message
/// require `Clone` locally.
///
/// With the `serde` feature, a message must also implement
/// `serde::Serialize` and `serde::de::DeserializeOwned`.
#[cfg(not(feature = "serde"))]
pub trait Message: LocalMessage {}
#[cfg(not(feature = "serde"))]
impl<T: LocalMessage> Message for T {}

/// A value that can be sent to an actor.
///
/// Messages need not be cloneable. APIs that fan out or repeat a message
/// require `Clone` locally.
///
/// The `serde` feature is enabled, so a message must also implement
/// [`serde::Serialize`] and [`serde::de::DeserializeOwned`] and can be sent
/// to an actor on another machine. Creating an actor whose message type
/// does not implement them fails to compile:
///
/// ```compile_fail
/// use picard::actors::*;
///
/// #[derive(Debug)]
/// struct NotSerializable;
///
/// #[derive(Default)]
/// struct MyActor;
///
/// impl Actor for MyActor {
///     type Msg = NotSerializable;
///     fn recv(&mut self, _: &Context<Self::Msg>, _: Self::Msg, _: Sender) {}
/// }
///
/// let sys = ActorSystem::new().unwrap();
/// sys.actor_of::<MyActor>("my-actor").unwrap();
/// ```
#[cfg(feature = "serde")]
pub trait Message: LocalMessage + serde::Serialize + serde::de::DeserializeOwned {}
#[cfg(feature = "serde")]
impl<T: LocalMessage + serde::Serialize + serde::de::DeserializeOwned> Message for T {}

#[doc(hidden)]
pub mod __private {
    #[cfg(feature = "serde")]
    pub use serde;
}

/// Wraps the message enum generated by `#[actor]`, adding the `serde`
/// derives when the `serde` feature is enabled.
#[doc(hidden)]
#[cfg(feature = "serde")]
#[macro_export]
macro_rules! __actor_msg_enum {
    ($($item:tt)*) => {
        #[derive(
            $crate::__private::serde::Serialize,
            $crate::__private::serde::Deserialize
        )]
        #[serde(crate = "::picard::__private::serde", bound = "")]
        $($item)*
    };
}

#[doc(hidden)]
#[cfg(not(feature = "serde"))]
#[macro_export]
macro_rules! __actor_msg_enum {
    ($($item:tt)*) => {
        $($item)*
    };
}

type CloneMessage = fn(&(dyn Any + Send)) -> Box<dyn Any + Send>;

pub struct AnyMessage {
    msg: Option<Box<dyn Any + Send>>,
    clone_message: Option<CloneMessage>,
}

pub struct DowncastAnyMessageError;

impl AnyMessage {
    pub fn new<T>(msg: T) -> Self
    where
        T: Any + LocalMessage,
    {
        Self {
            msg: Some(Box::new(msg)),
            clone_message: None,
        }
    }

    pub fn new_repeatable<T>(msg: T) -> Self
    where
        T: Any + LocalMessage + Clone,
    {
        fn clone_message<T: Any + Send + Clone>(msg: &(dyn Any + Send)) -> Box<dyn Any + Send> {
            Box::new(
                msg.downcast_ref::<T>()
                    .expect("stored message type must match its clone function")
                    .clone(),
            )
        }

        Self {
            msg: Some(Box::new(msg)),
            clone_message: Some(clone_message::<T>),
        }
    }

    /// Take the message out as a `T`. A repeatable message is cloned and stays
    /// available.
    ///
    /// # Errors
    ///
    /// Returns [`DowncastAnyMessageError`] if the message was already taken
    /// or is not a `T`.
    pub fn take<T>(&mut self) -> Result<T, DowncastAnyMessageError>
    where
        T: Any + LocalMessage,
    {
        let Some(stored) = self.msg.as_ref() else {
            return Err(DowncastAnyMessageError);
        };
        if !stored.is::<T>() {
            return Err(DowncastAnyMessageError);
        }

        let msg = if let Some(clone_message) = self.clone_message {
            clone_message(stored.as_ref())
        } else {
            self.msg.take().ok_or(DowncastAnyMessageError)?
        };
        msg.downcast::<T>()
            .map(|msg| *msg)
            .map_err(|_| DowncastAnyMessageError)
    }
}

impl Debug for AnyMessage {
    fn fmt(&self, f: &mut fmt::Formatter) -> fmt::Result {
        f.write_str("AnyMessage")
    }
}

